import { expect, test, type Page } from '@playwright/test'
import { completeQuestionnaire } from './questionnaire-helpers'
import { browserSources } from '../../src/features/assessment/browser-sources'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'

async function captureBoth(page: Page, name: string) {
  await expect(page.locator('h1')).toBeVisible()
  const directory = path.join(process.cwd(), 'playwright-report', 'club-visuals')
  await mkdir(directory, { recursive: true })
  for (const [kind, width, height] of [['desktop',1440,900],['mobile',390,844]] as const) {
    await page.setViewportSize({ width, height })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: path.join(directory, name + '-' + kind + '.png'), fullPage: true })
  }
  await page.setViewportSize({ width:1440, height:900 })
}
